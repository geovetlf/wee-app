/*
 * DANÉS — WEË FILMMAKER, «Varias escenas» (F1-C y F1-D): la producción en la app, el storyboard, el panel
 * Instruktion (Director), lo que el dominio dice con códigos (val*, op*, rec*, req*, per*) y la toma de un plano.
 *
 * Tipado contra el español: si allí hay una clave que aquí falta, no compila.
 *
 * Se tutea («du») y todo va en mayúscula de frase. El nombre de la experiencia es «Flere scener», que TIENE que ser
 * el mismo que `studio.xpMultiScene` (lo comprueba `filmmaker-i18n.test.mjs`, F3).
 *
 * LAS TRES PIEZAS DE UNA PRODUCCIÓN (glosario § 9.6). La escena es «scene» (scener, género común). El plano es
 * «klip» (neutro e invariable: «1 klip», «3 klip», «dit klip», «et nyt klip»); el término de cine, «indstilling»,
 * se descartó porque choca con «Indstillinger» (Configuración). La TOMA —cada vídeo que Weë genera para un plano,
 * que se puede repetir— es «version» (común), la palabra con la que el resto de Weë dice «hazlo otra vez»; «take» y
 * «optagelse» se descartaron porque hablan de rodar, no de generar. Como «scene» y «version» son comunes y «klip»
 * neutro, los motivos de F1-D, que hablan de un plano o de una escena sin decir cuál, se escriben SIN pronombre que
 * dependa del género («Der bruges referencer…», «Det, du vil generere, findes ikke…»).
 *
 * El storyboard es «Storyboard» (préstamo de la Retskrivningsordbogen, guía § 3) y el panel Director,
 * «Instruktion»; dirigir una escena o un plano, «instruere» («Instruer {{nombre}}», sin acento: no es ambiguo). La
 * duración es «Varighed»: «Målvarighed», «Samlet varighed». La proporción es «Billedforhold» y «Formato», «Format».
 * Los personajes son «Karakterer», su vestuario, «påklædning», y una línea de diálogo, «replik» (pl. «replikker»).
 * «Amanecer» y «Atardecer» son «Solopgang» y «Solnedgang», la pareja exacta del español. «Mediodía» es «Midt på
 * dagen» y no «Middag», que en danés es también la cena. «Medio cuerpo» y «Cuerpo entero» son «Halvfigur» y
 * «Helfigur», como en la fotografía danesa. El tiempo, como lo escribe DMI: «Klart», «Skyet», «Overskyet»,
 * «Tordenvejr» (tormenta con truenos; «Storm» en danés es solo viento fuerte), «Blæsende». «Narrador» es
 * «Fortællerstemme» (glosario § 9.6) y «Ambiente», «Baggrundslyd». El coste es «Pris» (glosario § 9.6).
 *
 * «Historias» (el formato de las redes, junto a TikTok y YouTube Shorts) es «Stories», como lo dice quien publica en
 * danés; DISTINTO a propósito de «historier», que son relatos escritos con Weë Writer. Archivar es «Arkivér» (con
 * acento, lista cerrada de la guía § 3) y desarchivar, «Fjern fra arkiv», como Google en danés. Duplicar,
 * «Dupliker» (sin acento: no es ambiguo). Dividir es «Opdel» y NO «Del», que en Weë es Compartir. Cobrar es «trække»
 * Credits (glosario § 9.6) y la devolución, «få tilbage».
 *
 * «Subir» y «Bajar» reordenan escenas y planos: «Flyt op» y «Flyt ned», no movimientos de cámara.
 *
 * «Escena 1 · Plano 2» es «Scene 1 · klip 2»: solo la primera palabra va en mayúscula (guía § 3).
 *
 * Los errores que se pintan como TÍTULO (`loadError`, `listError`, `saveError`) o delante de otra frase
 * (`createError`, en «{{donde}}: {{frase}}») van sin punto; el resto, frase completa con punto (guía § 2). Los
 * segundos se escriben «s» (símbolo SI, compacto en botones y chips), con espacio fijo (U+00A0) entre la cifra y la
 * unidad, igual que «Credits» (guía § 5).
 *
 * Se escriben igual que en español o en inglés porque no se traducen o ya son danés: TikTok, YouTube y YouTube
 * Shorts (plataformas), «Format», «Storyboard», «Standard» y «Dialog». Weë, Weë Studio y Credits son marca y no se
 * declinan («din Weë-konto»).
 */
